"""Suite runner: every task, several runs, consistency metrics.

Each task runs ``RUNS`` times. Two aggregates matter:

- **pass@3** — at least one of the three runs passed. A lucky agent
  scores well here.
- **pass^3** — all three runs passed. Reliability lives here: doing the
  right thing once is an anecdote; doing it every time, in the right
  order, under the same constraints, is the property being measured.

Both agents in this repo are deterministic, so their repeated runs are
identical by construction; the metrics are computed honestly anyway,
and the test-suite verifies the math against a deliberately flaky stub
agent, because the moment an LLM drives these tasks the distinction
becomes the whole story.
"""

from __future__ import annotations

import html

from tasks.definitions import SUITES
from tasks.runner import run_task

from .checks import CHECK_NAMES, score_run

RUNS = 3


def pass_at_k(run_passes: list[bool]) -> bool:
    """At least one run passed."""
    return any(run_passes)


def pass_hat_k(run_passes: list[bool]) -> bool:
    """Every run passed."""
    return bool(run_passes) and all(run_passes)


def run_suite(agent_cls, tasks: list[dict], runs: int = RUNS) -> list[dict]:
    """Run one agent over a list of tasks; one result dict per task."""
    results = []
    for task in tasks:
        run_checks = []
        for _ in range(runs):
            record = run_task(agent_cls, task)
            run_checks.append(score_run(task, record))
        passes = [c["passed"] for c in run_checks]
        failures: dict[str, int] = {}
        for checks in run_checks:
            for name in CHECK_NAMES:
                if not checks[name]:
                    failures[name] = failures.get(name, 0) + 1
        results.append({
            "task_id": task["id"],
            "suite": task["suite"],
            "agent": agent_cls.name,
            "runs": run_checks,
            "pass_at": pass_at_k(passes),
            "pass_hat": pass_hat_k(passes),
            "check_failures": failures,
        })
    return results


def run_all(agent_classes: list, runs: int = RUNS) -> dict:
    """Run every agent over every suite. Returns nested results."""
    out: dict = {}
    for agent_cls in agent_classes:
        out[agent_cls.name] = {
            suite: run_suite(agent_cls, tasks, runs)
            for suite, tasks in SUITES.items()
        }
    return out


def suite_pass_hat(results: list[dict]) -> tuple[int, int]:
    passed = sum(1 for r in results if r["pass_hat"])
    return passed, len(results)


def headline_rows(all_results: dict) -> list[dict]:
    """One row per agent per suite, plus totals — the README table."""
    rows = []
    for agent, suites in all_results.items():
        total_pass = total_tasks = 0
        row = {"agent": agent}
        for suite, results in suites.items():
            passed, count = suite_pass_hat(results)
            row[suite] = (passed, count)
            total_pass += passed
            total_tasks += count
        row["total"] = (total_pass, total_tasks)
        rows.append(row)
    return rows


def _pct(pair: tuple[int, int]) -> str:
    passed, count = pair
    return f"{passed}/{count}"


def render_markdown(all_results: dict) -> str:
    lines = [
        "# Benchmark results",
        "",
        ("pass^3 per suite (all 3 runs of a task passed) — generated by "
         "`scripts/run_benchmark.py` from a real run."),
        "",
        "| Agent | Base | Hallucination | Disambiguation | Total |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in headline_rows(all_results):
        lines.append(
            f"| {row['agent']} | {_pct(row['base'])} | "
            f"{_pct(row['hallucination'])} | {_pct(row['disambiguation'])} | "
            f"{_pct(row['total'])} |"
        )
    lines += ["", "## Per-task detail", ""]
    for agent, suites in all_results.items():
        lines.append(f"### Agent: {agent}")
        lines.append("")
        lines.append("| Task | Suite | pass@3 | pass^3 | Failed checks (of 3 runs) |")
        lines.append("| --- | --- | --- | --- | --- |")
        for suite, results in suites.items():
            for r in results:
                failed = ", ".join(
                    f"{k}×{v}" for k, v in sorted(r["check_failures"].items())
                ) or "—"
                lines.append(
                    f"| {r['task_id']} | {suite} | "
                    f"{'yes' if r['pass_at'] else 'no'} | "
                    f"{'yes' if r['pass_hat'] else 'no'} | {failed} |"
                )
        lines.append("")
    return "\n".join(lines)


def render_html(all_results: dict) -> str:
    rows_html = []
    for row in headline_rows(all_results):
        rows_html.append(
            "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>".format(
                html.escape(row["agent"]),
                _pct(row["base"]),
                _pct(row["hallucination"]),
                _pct(row["disambiguation"]),
                _pct(row["total"]),
            )
        )
    return (
        "<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        "<title>Agent reliability benchmark</title></head><body>"
        "<h1>Agent reliability benchmark — pass^3 by suite</h1>"
        "<table border=\"1\" cellspacing=\"0\" cellpadding=\"6\">"
        "<tr><th>Agent</th><th>Base</th><th>Hallucination</th>"
        "<th>Disambiguation</th><th>Total</th></tr>"
        + "".join(rows_html)
        + "</table></body></html>\n"
    )
